import { test, expect } from 'claude-code/testing'

const edit = (file_path: string) =>
  ({ tool: 'Edit', file_path, old_string: 'a', new_string: 'b' }) as const

test('denies an Edit to the generated trips.csv', async ($, on) => {
  let reached = false
  on('tool.call', () => {
    reached = true
    throw new Error('the bottom should never be reached on a deny')
  })
  const r = await $.tool.call(edit('/repo/data/trips.csv'))
  expect(reached).toBe(false)
  expect(r.deny ?? r.text).toContain('generated by data/build_data.R')
})

test('lets an Edit to the generator through to the bottom', async ($, on) => {
  let reached = false
  on('tool.call', ($, e) => {
    reached = true
    return {
      result: { filePath: e.file_path, oldString: 'a', newString: 'b', originalFile: null, structuredPatch: [], userModified: false, replaceAll: false },
      text: 'edited',
      isError: false,
    }
  })
  await $.tool.call(edit('/repo/data/build_data.R'))
  expect(reached).toBe(true)
})

test('relays a failed Bash result unchanged', async ($, on) => {
  on('tool.call', () => ({
    result: { stdout: '', stderr: 'ls: /nonexistent: No such file or directory', interrupted: false },
    text: 'ls: /nonexistent: No such file or directory',
    isError: true,
  }))
  const r = await $.tool.call({ tool: 'Bash', command: 'ls /nonexistent' })
  expect(r.isError).toBe(true)
})
