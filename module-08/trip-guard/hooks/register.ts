import type { Register } from 'claude-code'

// The generated data file. Edit data/build_data.R instead.
const GENERATED = /(^|\/)data\/trips\.csv$/
// A Bash command that could rewrite it: the file name next to an in-place
// edit flag, a redirection, or a copy/move/delete/tee. Reads (cat, head,
// awk without -i, grep) pass.
const BASH_WRITE = /trips\.csv/.source
const WRITES = new RegExp(
  `(?:\\b(?:sed|perl)\\s+[^|;]*-[a-zA-Z]*i\\b[^|;]*${BASH_WRITE})|(?:>>?\\s*\\S*${BASH_WRITE})|(?:\\b(?:tee|mv|cp|rm|truncate)\\b[^|;]*${BASH_WRITE})|(?:${BASH_WRITE}[^|;]*\\b(?:write\\.csv|to_csv)\\b)|(?:\\b(?:write\\.csv|to_csv)\\b[^|;]*${BASH_WRITE})`,
)

function why(plugin: string, what: string) {
  return `${plugin}: ${what} is generated by data/build_data.R; edit the generator instead.`
}

export const register: Register = on => {

  // 1. A guard on the file tools: deny any Edit or Write that targets the CSV.
  //    The .catch answers in the hook's place if the hook itself fails before
  //    it decided; a guard that throws would otherwise be skipped.
  for (const tool of ['Edit', 'Write'] as const) {
    on('tool.call', { tool }, ($, e, next) =>
      GENERATED.test(e.file_path) ? { deny: why($.plugin.name, e.file_path) } : next(e),
    ).catch(($, e, next) =>
      next.called ? next(e) : { deny: `${$.plugin.name}: its guard failed, so the edit is refused.` },
    )
  }

  // 2. The same guard on Bash, because `sed -i` and `> data/trips.csv` are
  //    edits too. Then the status line: after the command ran, show it if it
  //    failed, clear the line if it succeeded.
  on('tool.call', { tool: 'Bash' }, async ($, e, next) => {
    if (WRITES.test(e.command)) return { deny: why($.plugin.name, 'data/trips.csv') }
    const ran = await next(e)
    const failed = ran.deny === undefined && ran.isError === true
    $.ui.status(failed ? `failed: ${e.command.slice(0, 40)}` : undefined)
    return ran
  }).catch(($, e, next) =>
    next.called ? next(e) : { deny: `${$.plugin.name}: its guard failed, so the command is refused.` },
  )

  // 3. A toast: when a turn took longer than a minute, say so.
  on('turn.complete', ($, e, next) => {
    if (e.durationMs > 60_000) {
      $.ui.toast(`${$.plugin.name}: that turn took ${Math.round(e.durationMs / 1000)} s`)
    }
    return next(e)
  })
}
