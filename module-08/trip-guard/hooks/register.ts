import type { Register } from 'claude-code'

// The generated data file. Edit data/build_data.R instead.
const GENERATED = /(^|\/)data\/trips\.csv$/

export const register: Register = on => {
  // 1. A guard: deny any Edit or Write that targets the generated CSV.
  //    The .catch answers in the hook's place if the hook itself fails
  //    before it decided; a guard that throws would otherwise be skipped
  //    and the edit would go through.
  for (const tool of ['Edit', 'Write'] as const) {
    on('tool.call', { tool }, ($, e, next) =>
      GENERATED.test(e.file_path)
        ? { deny: `${$.plugin.name}: ${e.file_path} is generated by data/build_data.R; edit the generator instead.` }
        : next(e),
    ).catch(($, e, next) =>
      next.called ? next(e) : { deny: `${$.plugin.name}: its guard failed, so the edit is refused.` },
    )
  }

  // 2. A status line: after each Bash call, show the command if it failed,
  //    clear the line if it succeeded.
  on('tool.call', { tool: 'Bash' }, async ($, e, next) => {
    const ran = await next(e)
    const failed = ran.deny === undefined && ran.isError === true
    $.ui.status(failed ? `failed: ${e.command.slice(0, 40)}` : undefined)
    return ran
  }).catch(($, e, next) => next(e))

  // 3. A toast: when a turn took longer than a minute, say so.
  on('turn.complete', ($, e, next) => {
    if (e.durationMs > 60_000) {
      $.ui.toast(`${$.plugin.name}: that turn took ${Math.round(e.durationMs / 1000)} s`)
    }
    return next(e)
  })
}
